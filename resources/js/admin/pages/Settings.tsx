/*
 * The Settings screen: the sections in one fixed order, never tabs, and a sticky save bar. General
 * holds the currency and the default language; Booking page the brand, the Theme picker first, the
 * Links card with the hosted page's link, the snippet generated by the server from the slug and
 * the saved theme, never typed, and one link per offered service and member with its QR code,
 * LinksCard, and the business page's text with Important info, ProfileFields, carried by the
 * settings Save, and under it the cover and the gallery; Booking rules the four numbers and the
 * start interval, a select of the intervals on the granularity; Opening hours the weekly editor
 * while the staff feature is absent; Payments, on every plan, the tenant's payment provider,
 * generated from the registry; Emails one checkbox per message of the catalog, reading the off
 * list the other way round, each tagged with who it goes to, and a message the server holds on
 * checked and disabled with the sentence saying why. After the form, and outside it since nothing
 * in it is saved, Danger zone, the seventh section on every plan: Export everything and Close this
 * account, DangerZone, for a viewer holding manageSettings, the close's day and way back from the
 * page's close prop, its words the billing section's.
 *
 * Nothing is optimistic. Save sends the whole patch every time and is disabled unless every rule
 * holds; on success the settings fields alone are re-seeded from the server's answer, and only the
 * page's own landed save re-seeds them, so a background refetch never clobbers an edit. The week,
 * the logo's and the cover's upload and removal, and the gallery's add and removal are their own
 * writes with their own buttons, because two writes that can fail independently get two buttons,
 * and each landed write re-seeds its own control and nothing else: a settings save leaves an
 * unsaved week and a chosen file where they are, and the hours save and an upload leave the
 * settings fields' edits alone in turn. The Payments section's eight writes are the page's too, so
 * while any one write is in flight the others are disabled with the reason stated in text.
 */

